-- Учебная база «TaskFlow» (SQLite) для SQL-песочницы и задачника сайта.
-- Повторяет таблицы TaskFlow из API_SPEC.md §7: users, projects, project_members, tasks,
-- comments, labels, task_labels, audit_log. Значения enum — как в спецификации:
--   users.role: USER | ADMIN;  projects.status: ACTIVE | ARCHIVED;
--   project_members.role: OWNER | MANAGER | VIEWER | ADMIN;
--   tasks.status: TODO | IN_PROGRESS | DONE;  tasks.priority: LOW | MEDIUM | HIGH.
-- Даты — ISO-текст UTC ('2026-03-14T09:30:00Z'); булево is_active — 0/1 (в SQLite нет BOOLEAN).
-- Данные выдуманные, совпадения с реальными людьми случайны.
--
-- Ловушки (заложены специально, на них строятся задачи):
--   * мягкое удаление: deleted_at у пользователей, проектов, задач и комментариев — «удалённые»
--     строки физически в таблице, их надо отсекать условием deleted_at IS NULL;
--   * удалён проект 8 «Пилот: чат-бот» — его задачи тоже помечены удалёнными (каскад API);
--   * неактивные пользователи (is_active = 0), среди них неактивный ADMIN;
--   * однофамильцы (Петров, Иванов, Морозова/Морозов) и полные тёзки — два «Сергея Иванова»;
--   * один и тот же email в разном регистре: ivan.petrov@... и IVAN.PETROV@...;
--   * повторная регистрация: email удалённого пользователя снова занят активным (частичный
--     уникальный индекс WHERE deleted_at IS NULL это разрешает);
--   * assignee_id = NULL у части задач; задачи, назначенные неактивному и удалённому пользователю,
--     и задача, назначенная не участнику проекта;
--   * description: NULL у одних задач и пустая строка '' у других — это разные вещи;
--   * дубли названий задач внутри проекта;
--   * проект 7 без задач, метка «архитектура» без задач, пользователи без проектов,
--     задачи без комментариев — материал для LEFT JOIN «без пары»;
--   * комментарии к удалённым задачам и удалённые комментарии;
--   * audit_log: user_id = NULL у системных записей, details — JSON-текст или NULL;
--   * в именах есть «ё» (Соловьёва, Семёнова, Фёдорова): поиск по «Соловьева» не найдёт.

PRAGMA foreign_keys = ON;

CREATE TABLE users (
  id            INTEGER PRIMARY KEY,
  email         TEXT    NOT NULL,
  password_hash TEXT    NOT NULL,
  first_name    TEXT    NOT NULL,
  last_name     TEXT    NOT NULL,
  role          TEXT    NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
  is_active     INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at    TEXT    NOT NULL,
  updated_at    TEXT    NOT NULL,
  deleted_at    TEXT
);
-- email уникален только среди неудалённых (как частичный индекс в TaskFlow)
CREATE UNIQUE INDEX ux_users_email_active ON users (email) WHERE deleted_at IS NULL;

CREATE TABLE projects (
  id          INTEGER PRIMARY KEY,
  name        TEXT    NOT NULL,
  description TEXT,
  status      TEXT    NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'ARCHIVED')),
  owner_id    INTEGER NOT NULL REFERENCES users (id),
  created_at  TEXT    NOT NULL,
  deleted_at  TEXT
);
CREATE INDEX ix_projects_owner_id ON projects (owner_id);

CREATE TABLE project_members (
  project_id INTEGER NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  user_id    INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role       TEXT    NOT NULL CHECK (role IN ('OWNER', 'MANAGER', 'VIEWER', 'ADMIN')),
  created_at TEXT    NOT NULL,
  PRIMARY KEY (project_id, user_id)
);
CREATE INDEX ix_project_members_user_id ON project_members (user_id);

CREATE TABLE tasks (
  id          INTEGER PRIMARY KEY,
  project_id  INTEGER NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  assignee_id INTEGER REFERENCES users (id),
  title       TEXT    NOT NULL,
  description TEXT,
  status      TEXT    NOT NULL DEFAULT 'TODO' CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
  priority    TEXT    NOT NULL DEFAULT 'MEDIUM' CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
  created_at  TEXT    NOT NULL,
  deleted_at  TEXT
);
CREATE INDEX ix_tasks_project_id ON tasks (project_id);
CREATE INDEX ix_tasks_assignee_id ON tasks (assignee_id);
CREATE INDEX ix_tasks_status ON tasks (status);
CREATE INDEX ix_tasks_priority ON tasks (priority);

CREATE TABLE comments (
  id         INTEGER PRIMARY KEY,
  task_id    INTEGER NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
  author_id  INTEGER NOT NULL REFERENCES users (id),
  text       TEXT    NOT NULL,
  created_at TEXT    NOT NULL,
  deleted_at TEXT
);
CREATE INDEX ix_comments_task_id ON comments (task_id);

CREATE TABLE labels (
  id   INTEGER PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE task_labels (
  task_id  INTEGER NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
  label_id INTEGER NOT NULL REFERENCES labels (id) ON DELETE CASCADE,
  PRIMARY KEY (task_id, label_id)
);

CREATE TABLE audit_log (
  id          INTEGER PRIMARY KEY,
  user_id     INTEGER REFERENCES users (id),
  action      TEXT    NOT NULL,
  entity_type TEXT    NOT NULL,
  entity_id   INTEGER NOT NULL,
  details     TEXT,
  created_at  TEXT    NOT NULL
);
CREATE INDEX ix_audit_log_user_id ON audit_log (user_id);
CREATE INDEX ix_audit_log_action ON audit_log (action);

