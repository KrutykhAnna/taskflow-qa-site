-- Учебная база «Магазин» (SQLite) — классика SQL-собеседований.
-- Таблицы: customers, categories, products, orders, order_items, employees, departments.
-- Даты — ISO-текст 'YYYY-MM-DD'; цены — REAL в рублях с копейками; зарплаты — INTEGER.
-- Данные выдуманные, совпадения с реальными людьми случайны.
--
-- Ловушки (заложены специально, на них строятся задачи):
--   * клиенты без заказов и заказы без позиций (order_items) — LEFT JOIN «без пары»;
--   * товары без категории (category_id = NULL), категория без товаров, товар, который ни разу не заказывали;
--   * у клиентов city и phone бывают NULL; город «Москва» встречается и как «москва»;
--   * зарплаты повторяются: две одинаковые максимальные — «вторая по величине» нужна через DISTINCT;
--   * employees.manager_id → employees.id (self-join), у директора руководителя нет (NULL);
--   * сотрудник без отдела (department_id = NULL) и отдел без сотрудников;
--   * order_items.price — цена на момент заказа, она может отличаться от текущей products.price;
--   * заказы за 2024 и 2025 годы, есть отменённые (status = 'cancelled') — их обычно не считают в выручке;
--   * у двух клиентов одинаковые имя и фамилия (разные люди, разные email).

PRAGMA foreign_keys = ON;

CREATE TABLE departments (
  id   INTEGER PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE employees (
  id            INTEGER PRIMARY KEY,
  first_name    TEXT    NOT NULL,
  last_name     TEXT    NOT NULL,
  department_id INTEGER REFERENCES departments (id),
  manager_id    INTEGER REFERENCES employees (id),
  salary        INTEGER NOT NULL CHECK (salary > 0),
  hire_date     TEXT    NOT NULL
);

CREATE TABLE categories (
  id   INTEGER PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE products (
  id          INTEGER PRIMARY KEY,
  name        TEXT    NOT NULL,
  category_id INTEGER REFERENCES categories (id),
  price       REAL    NOT NULL CHECK (price >= 0),
  stock       INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE customers (
  id            INTEGER PRIMARY KEY,
  first_name    TEXT NOT NULL,
  last_name     TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE,
  city          TEXT,
  phone         TEXT,
  registered_at TEXT NOT NULL
);

CREATE TABLE orders (
  id          INTEGER PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers (id),
  order_date  TEXT    NOT NULL,
  status      TEXT    NOT NULL CHECK (status IN ('new', 'paid', 'shipped', 'cancelled'))
);

CREATE TABLE order_items (
  id         INTEGER PRIMARY KEY,
  order_id   INTEGER NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products (id),
  quantity   INTEGER NOT NULL CHECK (quantity > 0),
  price      REAL    NOT NULL
);

